const router=require('express').Router();
const {authenticateToken}=require('../middlewares/authMiddleware');
const c=require('../controllers/week5Controller');
router.use(authenticateToken);
const calendar=require('../controllers/calendarController');
const jobs=require('../controllers/jobController');
const branches=require('../controllers/branchController');
router.get('/branches',branches.list);
router.post('/branches',branches.create);
router.patch('/branches/:id',branches.rename);
router.get('/jobs',jobs.catalog);
router.post('/jobs',jobs.create);
router.patch('/jobs/:id',jobs.edit);
router.put('/employees/:id/jobs',jobs.permissions);
router.put('/shifts/:id/jobs',jobs.requirements);
router.post('/roster-publications',jobs.publish);
router.get('/calendar',calendar.calendar);
router.post('/weekly-registrations',require('../controllers/registrationController').register);
router.patch('/shifts/:id/capacity',calendar.configure);
router.post('/employees/:id/account',c.createAccount);
router.get('/attendance',c.listAttendance);
router.post('/attendance/check-in',c.checkIn);
router.post('/attendance/check-out',c.checkOut);
router.get('/leave-requests',c.listLeave);
router.post('/leave-requests',c.createLeave);
router.patch('/leave-requests/:id',c.reviewLeave);
router.get('/shift-change-requests',c.listChange);
router.post('/shift-change-requests',c.createChange);
router.patch('/shift-change-requests/:id',c.reviewChange);
module.exports=router;
